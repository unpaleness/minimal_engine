    const std::vector<const char*> VALIDATION_LAYERS{"VK_LAYER_KHRONOS_validation"};
    const std::vector<const char*> DEVICE_EXTENSIONS{VK_KHR_SWAPCHAIN_EXTENSION_NAME};
